#!/usr/bin/env bash
# Builds @pikos/recurrence-wasm from the Rust recurrence engine, via Docker only (no local Rust
# toolchain or wasm-bindgen CLI):
#   crates/pikos-recurrence -> crates/pikos-recurrence-wasm -> packages/recurrence-wasm/pkg
#
# pkg/ is committed so JS-only development never needs Rust. Re-run and commit it whenever the
# engine or bindings change.
#
# The compile runs in a pinned Linux image because rustc's wasm output depends on the host it
# runs on, which no flag can pin away: the same commit and toolchain gave 269,840 bytes on
# aarch64-apple-darwin and 269,030 on x86_64-linux. Each host reproduces itself, so the artifact
# only round-trips if every machine compiles on the same one. The rustc pin and path remaps
# below still matter for that.

set -euo pipefail
cd "$(dirname "$0")/.."

PKG_DIR="packages/recurrence-wasm/pkg"
WASM_BINDGEN_PIN=$(sed -n 's/^wasm-bindgen = "=\(.*\)"$/\1/p' crates/pikos-recurrence-wasm/Cargo.toml)

# `stable` would go red the day rustc bumps, since its version moves codegen and panic line
# tables. The image tag pins toolchain and host together, and RUSTUP_TOOLCHAIN keeps the repo's
# rust-toolchain.toml from swapping in the app's compiler inside the container.
RUSTC_PIN="1.93.1"
BUILD_IMAGE="rust:${RUSTC_PIN}-slim"
BUILD_PLATFORM="linux/amd64"

if ! docker info >/dev/null 2>&1; then
  echo "Docker is required: the artifact is only reproducible when compiled" >&2
  echo "inside ${BUILD_IMAGE} (${BUILD_PLATFORM}). Start Docker and retry." >&2
  exit 1
fi

docker run --rm \
  --platform "$BUILD_PLATFORM" \
  -v "$PWD:/work" \
  -w /work \
  -e PKG_DIR="$PKG_DIR" \
  -e WASM_BINDGEN_PIN="$WASM_BINDGEN_PIN" \
  -e HOST_OWNER="$(id -u):$(id -g)" \
  -e RUSTUP_TOOLCHAIN="$RUSTC_PIN" \
  "$BUILD_IMAGE" \
  bash -euo pipefail -c '
    apt-get update -qq >/dev/null
    apt-get install -y -qq curl ca-certificates >/dev/null
    rustup target add wasm32-unknown-unknown >/dev/null

    curl -fsSL "https://github.com/wasm-bindgen/wasm-bindgen/releases/download/${WASM_BINDGEN_PIN}/wasm-bindgen-${WASM_BINDGEN_PIN}-x86_64-unknown-linux-musl.tar.gz" \
      | tar xz --strip-components=1 -C /usr/local/bin
    CLI_VERSION=$(wasm-bindgen --version | awk "{print \$2}")
    if [ "$CLI_VERSION" != "$WASM_BINDGEN_PIN" ]; then
      echo "wasm-bindgen CLI ${CLI_VERSION} != pinned ${WASM_BINDGEN_PIN}" >&2
      exit 1
    fi

    # Outside the mount: the host target/ holds objects fingerprinted for a
    # different host, and sharing the directory lets them collide.
    export CARGO_TARGET_DIR=/tmp/target

    # Panic locations bake in source paths carrying $HOME and the host triple;
    # ambient RUSTFLAGS would do the same. Both get fixed stand-ins.
    export RUSTFLAGS="--remap-path-prefix=${CARGO_HOME:-$HOME/.cargo}/registry/src=/cargo --remap-path-prefix=$(rustc --print sysroot)=/rustc"

    cargo build \
      -p pikos-recurrence-wasm \
      --target wasm32-unknown-unknown \
      --profile wasm-release

    rm -rf "$PKG_DIR"
    wasm-bindgen \
      --target web \
      --out-dir "$PKG_DIR" \
      "$CARGO_TARGET_DIR/wasm32-unknown-unknown/wasm-release/pikos_recurrence_wasm.wasm"

    chown -R "$HOST_OWNER" "$PKG_DIR"
  '

# Embed the wasm as base64 so consumers initialize synchronously with zero bundler config.
node - "$PKG_DIR" <<'EOF'
const fs = require("fs");
const path = require("path");
const pkgDir = process.argv[2];
const wasmPath = path.join(pkgDir, "pikos_recurrence_wasm_bg.wasm");
const b64 = fs.readFileSync(wasmPath).toString("base64");
fs.writeFileSync(
  path.join(pkgDir, "wasm_data.js"),
  "// Generated by scripts/build-recurrence-wasm.sh — do not edit.\n" +
    "// Base64 of pikos_recurrence_wasm_bg.wasm, embedded so the engine\n" +
    "// initializes synchronously in every runtime without asset plumbing.\n" +
    `export const WASM_BASE64 =\n  "${b64}";\n`
);
fs.writeFileSync(
  path.join(pkgDir, "wasm_data.d.ts"),
  "export declare const WASM_BASE64: string;\n"
);
// The raw .wasm is not shipped — the base64 module above is the artifact.
fs.unlinkSync(wasmPath);
const gitignore = path.join(pkgDir, ".gitignore");
if (fs.existsSync(gitignore)) fs.unlinkSync(gitignore);
console.log(`embedded ${(b64.length / 1024).toFixed(0)}KB base64 into ${pkgDir}/wasm_data.js`);
EOF

echo "OK: ${PKG_DIR} regenerated — commit the changes."
